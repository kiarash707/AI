export function LanguageToggle(){
 const locale=useLocale(),setLocale=useSetLocale();
 return <button type="button" className="language-toggle" onClick={()=>setLocale(locale==='fa'?'en':'fa')} aria-label={locale==='fa'?'Switch interface to English':'تغییر زبان به فارسی'} title={locale==='fa'?'Switch to English':'Change language to Persian'}>{locale==='fa'?'EN':'فارسی'}</button>;
}
export function LocaleProvider({children}:{children:React.ReactNode}){
 const [locale,setLocale]=useState<Locale>(()=>{try{return localStorage.getItem('kayro-ai-locale')==='en'?'en':'fa'}catch{return'fa'}});
 useEffect(()=>{try{localStorage.setItem('kayro-ai-locale',locale);document.documentElement.lang=locale;document.documentElement.dir=locale==='fa'?'rtl':'ltr'}catch{}},[locale]);
 const setter=useMemo(()=>setLocale,[]);
 return <LocaleContext.Provider value={locale}><SetLocaleContext.Provider value={setter}>{children}</SetLocaleContext.Provider></LocaleContext.Provider>;
}
